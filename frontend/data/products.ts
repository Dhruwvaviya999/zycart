export const brands = [...new Set(products.map((product) => product.brand))].sort();

export const priceBounds = {
  min: 0,
  max: Math.ceil(Math.max(...products.map((product) => product.price)) / 1000) * 1000,
};

export const trendingProducts = products.filter((product) =>
  ['p-009', 'p-001', 'p-012', 'p-022', 'p-034', 'p-017', 'p-025', 'p-010'].includes(product.id),
);

export const newArrivals = [...products]
  .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
  .slice(0, 8);

export const bestSellers = [...products].sort((a, b) => b.unitsSold - a.unitsSold).slice(0, 8);

export const editorsPicks = products.filter((product) =>
  ['p-005', 'p-019', 'p-027', 'p-013', 'p-035', 'p-023', 'p-029', 'p-011'].includes(product.id),
);

export function relatedProducts(product: Product, limit = 4) {
  return products
    .filter((candidate) => candidate.category === product.category && candidate.id !== product.id)
    .slice(0, limit);
}

export function alsoLike(product: Product, limit = 4) {
  return products
    .filter((candidate) => candidate.category !== product.category)
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}
